"""A one-click proof that the installation works end to end.

Generates a small sample locally, then runs it through the ordinary pipeline:
resolve, select, transfer, probe, finalize, sidecar. Nothing is fetched from
the internet and no credential is involved, so a green result isolates
"mediadl works here" from "that particular source or account has a problem".
"""
from __future__ import annotations

import struct
import zlib
from pathlib import Path

from mediadl.obs.logging import get_logger
from mediadl.processing.ffmpeg_runner import FfmpegTools

log = get_logger(__name__)

SAMPLE_DIR_NAME = 'sample'


def _png_chunk(kind: bytes, payload: bytes) -> bytes:
    return (
        struct.pack('>I', len(payload))
        + kind + payload
        + struct.pack('>I', zlib.crc32(kind + payload) & 0xFFFFFFFF)
    )


def write_sample_png(path: Path, size: int = 256) -> Path:
    """A real PNG built from scratch, so the sample needs no dependencies."""
    rows = bytearray()
    for y in range(size):
        rows.append(0)  # filter byte: none
        for x in range(size):
            rows += bytes(((x * 255) // size, (y * 255) // size, 160))
    header = struct.pack('>IIBBBBB', size, size, 8, 2, 0, 0, 0)  # 8-bit truecolour
    path.write_bytes(
        b'\x89PNG\r\n\x1a\n'
        + _png_chunk(b'IHDR', header)
        + _png_chunk(b'IDAT', zlib.compress(bytes(rows), 6))
        + _png_chunk(b'IEND', b'')
    )
    return path


def write_sample_video(tools: FfmpegTools, path: Path, seconds: int = 2) -> Path | None:
    """A 2-second clip, only when FFmpeg is available."""
    import subprocess

    try:
        subprocess.run(
            [
                tools.ffmpeg, '-nostdin', '-hide_banner', '-v', 'error',
                '-f', 'lavfi', '-i', f'testsrc2=size=320x240:rate=24:duration={seconds}',
                '-f', 'lavfi', '-i', f'sine=frequency=440:duration={seconds}',
                '-c:v', 'libx264', '-preset', 'ultrafast', '-crf', '32',
                '-pix_fmt', 'yuv420p', '-c:a', 'aac', '-b:a', '64k', '-shortest',
                '-y', str(path),
            ],
            check=True, capture_output=True, timeout=120,
        )
        return path
    except Exception as exc:
        log.warning('selftest_video_skipped', error=type(exc).__name__)
        return None


def prepare_sample(data_dir: Path, tools: FfmpegTools | None) -> tuple[Path, list[str]]:
    """Create the sample folder and report what went into it."""
    directory = data_dir / SAMPLE_DIR_NAME
    directory.mkdir(parents=True, exist_ok=True)
    for existing in directory.iterdir():
        if existing.is_file():
            existing.unlink()

    created = []
    write_sample_png(directory / 'sample-image.png')
    created.append('a 256x256 PNG, generated here')
    if tools is not None and write_sample_video(tools, directory / 'sample-video.mp4'):
        created.append('a 2-second H.264 + AAC clip, generated by FFmpeg')
    return directory, created
